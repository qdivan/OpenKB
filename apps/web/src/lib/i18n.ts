const TRANSLATIONS: Record<Locale, Record<string, string>> = {
  en: {},
  "zh-CN": ZH_CN_TRANSLATIONS
};

export function normalizeLocale(locale: string | null | undefined): Locale | null {
  if (!locale) {
    return null;
  }

  const normalized = locale.trim().toLowerCase();
  if (normalized === "en" || normalized.startsWith("en-")) {
    return "en";
  }
  if (normalized === "zh" || normalized.startsWith("zh-")) {
    return "zh-CN";
  }
  return null;
}

export function detectBrowserLocale(
  language?: string | null,
  languages?: readonly string[] | null
): Locale {
  const candidates = [...(languages ?? []), language ?? ""];
  for (const candidate of candidates) {
    const locale = normalizeLocale(candidate);
    if (locale) {
      return locale;
    }
  }
  return DEFAULT_LOCALE;
}

export function isSupportedLocale(locale: string | null | undefined): locale is Locale {
  return SUPPORTED_LOCALES.includes(locale as Locale);
}

export function interpolateTranslation(template: string, values: TranslationValues = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = values[key];
    return value === null || value === undefined ? match : String(value);
  });
}

export function translate(
  locale: Locale,
  key: string,
  values?: TranslationValues,
  fallback = key
): string {
  const template = TRANSLATIONS[locale][key] ?? TRANSLATIONS.en[key] ?? fallback;
  return interpolateTranslation(template, values);
}
